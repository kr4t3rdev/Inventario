import { describe, expect, it } from 'vitest';

import {
  buildCanonicalUrl,
  buildFaqSchema,
  buildOrganizationSchema,
  buildPublicPageUrls,
  buildSoftwareApplicationSchema,
  PRIVATE_ROUTE_PREFIXES,
  PUBLIC_ROUTE_PATHS,
  siteConfig,
  siteMetadata,
} from '@/lib/seo/site';

describe('site SEO helpers', () => {
  it.each([
    {
      input: '/',
      expected: siteConfig.url,
    },
    {
      input: 'docs',
      expected: `${siteConfig.url}/docs`,
    },
    {
      input: '/docs/guias/',
      expected: `${siteConfig.url}/docs/guias`,
    },
  ])('builds canonical URLs for $input', ({ input, expected }) => {
    expect(buildCanonicalUrl(input)).toBe(expected);
  });

  it('exposes descriptive root metadata from the site config', () => {
    expect(siteMetadata.title).toBe(siteConfig.name);
    expect(siteMetadata.description).toBe(siteConfig.defaultDescription);
    expect(siteMetadata.description).toContain('inventario');
    expect(siteMetadata.description).not.toBe('Generated by kr4t3rdev');
  });

  it('builds the organization schema', () => {
    const schema = buildOrganizationSchema();

    expect(schema['@context']).toBe('https://schema.org');
    expect(schema['@type']).toBe('Organization');
    expect(schema.name).toBe(siteConfig.name);
    expect(schema.url).toBe(siteConfig.url);
    expect(schema.description).toBe(siteConfig.defaultDescription);
  });

  it('builds the software application schema', () => {
    const schema = buildSoftwareApplicationSchema();

    expect(schema['@context']).toBe('https://schema.org');
    expect(schema['@type']).toBe('SoftwareApplication');
    expect(schema.name).toBe(siteConfig.name);
    expect(schema.url).toBe(siteConfig.url);
    expect(schema.description).toBe(siteConfig.defaultDescription);
    expect(schema.applicationCategory).toBe('BusinessApplication');
    expect(schema.operatingSystem).toBe('Web');
  });

  it('builds FAQ schema from visible question and answer content', () => {
    const schema = buildFaqSchema([
      {
        question: 'Que es FinanceMDM?',
        answer: 'Es una plataforma para gestionar inventario, ventas y contabilidad.',
      },
      {
        question: 'Para quien esta pensado?',
        answer: 'Para pymes que necesitan centralizar operacion y reportes.',
      },
    ]);

    expect(schema['@context']).toBe('https://schema.org');
    expect(schema['@type']).toBe('FAQPage');
    expect(schema.mainEntity).toEqual([
      {
        '@type': 'Question',
        name: 'Que es FinanceMDM?',
        acceptedAnswer: {
          '@type': 'Answer',
          text: 'Es una plataforma para gestionar inventario, ventas y contabilidad.',
        },
      },
      {
        '@type': 'Question',
        name: 'Para quien esta pensado?',
        acceptedAnswer: {
          '@type': 'Answer',
          text: 'Para pymes que necesitan centralizar operacion y reportes.',
        },
      },
    ]);
  });

  it('builds canonical URLs for the public route list', () => {
    expect(buildPublicPageUrls(PUBLIC_ROUTE_PATHS)).toEqual([
      siteConfig.url,
      `${siteConfig.url}/docs`,
    ]);
  });

  it('defines private route prefixes for robots rules', () => {
    expect(PRIVATE_ROUTE_PREFIXES).toEqual(['/busy', '/admin', '/api']);
  });
});
